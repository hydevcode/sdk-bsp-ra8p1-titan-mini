int OV5640_af_init(void)
{
    uint8_t reg3029 = 0;
    uint32_t total_len = sizeof(af_firmware_regs) / sizeof(af_firmware_regs[0]);
    uint32_t offset = 0;

    wrSensorReg16_8(0x3000, 0x20);

    while (offset < total_len) {
        uint32_t chunk_len = (total_len - offset > BURST_SIZE) ? BURST_SIZE : (total_len - offset);
        if (!wrSensorReg16_Multi(FOCUS_FW_DOWNLOAD_ADDR + offset, (uint8_t *)&af_firmware_regs[offset], chunk_len)) {
            return -RT_ERROR;
        }
        offset += chunk_len;
        rt_thread_mdelay(100);
    }

    wrSensorReg16_8(0x3022, 0x00);
    wrSensorReg16_8(0x3023, 0x00);
    wrSensorReg16_8(0x3024, 0x00);
    wrSensorReg16_8(0x3025, 0x00);
    wrSensorReg16_8(0x3026, 0x00);
    wrSensorReg16_8(0x3027, 0x00);
    wrSensorReg16_8(0x3028, 0x00);
    wrSensorReg16_8(0x3029, 0x7F);
    wrSensorReg16_8(0x3000, 0x00);

    rt_thread_mdelay(1000);

    int timeout = 0;

    while ((reg3029 != 0x70) && (timeout < TIMEOUT))
    {
        rt_thread_mdelay(1);
        rdSensorReg16_8( 0x3029, &reg3029);
        timeout++;
    }

    if (reg3029 != 0x70)
    {
        return RT_ERROR;
    }
    return RT_EOK;
}

int OV5640_auto_focus(void)
{
    if (!wrSensorReg16_8(REG_AF_CMD_MAIN, 0x03)) {
        return -RT_ERROR;
    }

    return RT_EOK;
}

int OV5640_release_focus(void)
{
    if (!wrSensorReg16_8(REG_AF_CMD_MAIN, 0x06)) {
        return -RT_ERROR;
    }
    return RT_EOK;
}
