static bool ov5640_register_is_critical(uint16_t reg)
{
    if (((reg >= 0x3000U) && (reg <= 0x3039U)) ||
        ((reg >= 0x3800U) && (reg <= 0x3824U)) ||
        ((reg >= 0x4200U) && (reg <= 0x4202U)) ||
        ((reg >= 0x4300U) && (reg <= 0x430DU)) ||
        ((reg >= 0x4602U) && (reg <= 0x460CU)) ||
        ((reg >= 0x4800U) && (reg <= 0x4837U)))
    {
        return true;
    }

    switch (reg)
    {
        case 0x3103:
        case 0x3108:
        case 0x5001:
        case 0x501f:
        case 0x503d:
            return true;
        default:
            return false;
    }
}

